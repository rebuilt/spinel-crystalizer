/* Crystal runtime for the proof-of-concept backend: the boxed value a
 * widened (poly) slot takes, the scalar operations it answers, and the
 * dynamic-dispatch seam (SpObject#sp_send) a widened object kind uses.
 *
 * Whole-program inference collapses a slot to `poly` when its values
 * disagree; the C backend represents that value as sp_RbVal (a tagged
 * union). Crystal has no `untyped` type, so this is the equivalent: a
 * closed union of the scalar types plus the SpObject base every emitted
 * class inherits, with CRuby-faithful rendering and arithmetic. SpValue is
 * a class (not a struct) so an expression that is only SOMETIMES poly -- a
 * method returning a concrete value on one path and a boxed one on another
 * -- type-checks as a union with SpValue in it. The typed fast path never
 * uses any of this. Generated once per program, ahead of every user class,
 * by codegen_program_crystal. */
#ifndef SPINEL_CRYSTAL_RUNTIME_H
#define SPINEL_CRYSTAL_RUNTIME_H

static const char *CR_RUNTIME =
  "abstract class SpObject\n"
  "  # The dynamic-dispatch seam: a widened value whose object kind is an emitted\n"
  "  # class answers through here. Each class with user methods overrides it.\n"
  "  def sp_send(name : String, args : Array(SpValue)) : SpValue\n"
  "    raise ArgumentError.new(\"undefined method '#{name}'\")\n"
  "  end\n"
  "end\n"
  "\n"
  "# A user object boxed into the value union. The object's own class does NOT\n"
  "# inherit SpObject: a common base widened a union of classes (and of class\n"
  "# objects) to `SpObject+`, which erased the emitter's per-class dispatch arms\n"
  "# (see P22). The box carries the object instead; the concrete T is known at\n"
  "# each SpBox(T) instantiation, so a per-class dispatch overload the emitter\n"
  "# generates resolves at compile time. Only OBJECTS are boxed in P22a; a stdlib\n"
  "# container still has no wrapper (that is a later step).\n"
  "class SpBox(T) < SpObject\n"
  "  getter val : T\n"
  "\n"
  "  def initialize(@val : T)\n"
  "  end\n"
  "\n"
  "  def inspect(io : IO) : Nil\n"
  "    @val.inspect(io)\n"
  "  end\n"
  "\n"
  "  def to_s(io : IO) : Nil\n"
  "    @val.to_s(io)\n"
  "  end\n"
  "end\n"
  "\n"
  "class SpValue\n"
  "  alias Raw = Int64 | Float64 | String | Symbol | Bool | Nil | SpObject | SpValue\n"
  "\n"
  "  @v : Raw\n"
  "\n"
  "  def initialize(@v : Raw)\n"
  "  end\n"
  "\n"
  "  def raw : Raw\n"
  "    @v\n"
  "  end\n"
  "\n"
  "  def inspect(io : IO) : Nil\n"
  "    @v.inspect(io)\n"
  "  end\n"
  "\n"
  "  def to_s(io : IO) : Nil\n"
  "    @v.to_s(io)\n"
  "  end\n"
  "\n"
  "  def ==(other : SpValue) : Bool\n"
  "    @v == other.raw\n"
  "  end\n"
  "\n"
  "  def ==(other : Raw) : Bool\n"
  "    @v == other\n"
  "  end\n"
  "\n"
  "  def hash(hasher)\n"
  "    @v.hash(hasher)\n"
  "  end\n"
  "\n"
  "  def truthy? : Bool\n"
  "    case v = @v\n"
  "    when Nil  then false\n"
  "    when Bool then v\n"
  "    else           true\n"
  "    end\n"
  "  end\n"
  "\n"
  "  def sp_nil? : Bool\n"
  "    @v.nil?\n"
  "  end\n"
  "\n"
  "  def to_i : Int64\n"
  "    case v = @v\n"
  "    when Int64   then v\n"
  "    when Float64 then v.to_i64\n"
  "    when String  then v.to_i64(strict: false) { 0_i64 }\n"
  "    when Bool    then v ? 1_i64 : 0_i64\n"
  "    else              0_i64\n"
  "    end\n"
  "  end\n"
  "\n"
  "  def to_f : Float64\n"
  "    case v = @v\n"
  "    when Int64   then v.to_f\n"
  "    when Float64 then v\n"
  "    when String  then v.to_f\n"
  "    when Bool    then v ? 1.0 : 0.0\n"
  "    else              0.0\n"
  "    end\n"
  "  end\n"
  "\n"
  "  def - : SpValue\n"
  "    case v = @v\n"
  "    when Int64   then SpValue.new(-v)\n"
  "    when Float64 then SpValue.new(-v)\n"
  "    else              raise ArgumentError.new(\"unsupported unary -\")\n"
  "    end\n"
  "  end\n"
  "\n"
  "  def +(other : SpValue) : SpValue\n"
  "    SpValue.new(sp_scalar_add(@v, other.raw))\n"
  "  end\n"
  "\n"
  "  def -(other : SpValue) : SpValue\n"
  "    SpValue.new(sp_scalar_sub(@v, other.raw))\n"
  "  end\n"
  "\n"
  "  def *(other : SpValue) : SpValue\n"
  "    SpValue.new(sp_scalar_mul(@v, other.raw))\n"
  "  end\n"
  "\n"
  "  def /(other : SpValue) : SpValue\n"
  "    SpValue.new(sp_scalar_div(@v, other.raw))\n"
  "  end\n"
  "\n"
  "  def <(other : SpValue) : Bool\n"
  "    sp_scalar_cmp(@v, other.raw) < 0\n"
  "  end\n"
  "\n"
  "  def <=(other : SpValue) : Bool\n"
  "    sp_scalar_cmp(@v, other.raw) <= 0\n"
  "  end\n"
  "\n"
  "  def >(other : SpValue) : Bool\n"
  "    sp_scalar_cmp(@v, other.raw) > 0\n"
  "  end\n"
  "\n"
  "  def >=(other : SpValue) : Bool\n"
  "    sp_scalar_cmp(@v, other.raw) >= 0\n"
  "  end\n"
  "\n"
  "  # A concrete operand beside a boxed one: box it on the fly. `x + 1` on a\n"
  "  # widened value is the common shape, and without these the emitter would have\n"
  "  # to box the operand at every arithmetic site. The SpValue overloads above\n"
  "  # stay more specific, so `x + y` on two boxed values still uses them.\n"
  "  def +(other : SpValue::Raw) : SpValue\n"
  "    SpValue.new(sp_scalar_add(@v, other))\n"
  "  end\n"
  "\n"
  "  def -(other : SpValue::Raw) : SpValue\n"
  "    SpValue.new(sp_scalar_sub(@v, other))\n"
  "  end\n"
  "\n"
  "  def *(other : SpValue::Raw) : SpValue\n"
  "    SpValue.new(sp_scalar_mul(@v, other))\n"
  "  end\n"
  "\n"
  "  def /(other : SpValue::Raw) : SpValue\n"
  "    SpValue.new(sp_scalar_div(@v, other))\n"
  "  end\n"
  "\n"
  "  def <(other : SpValue::Raw) : Bool\n"
  "    sp_scalar_cmp(@v, other) < 0\n"
  "  end\n"
  "\n"
  "  def <=(other : SpValue::Raw) : Bool\n"
  "    sp_scalar_cmp(@v, other) <= 0\n"
  "  end\n"
  "\n"
  "  def >(other : SpValue::Raw) : Bool\n"
  "    sp_scalar_cmp(@v, other) > 0\n"
  "  end\n"
  "\n"
  "  def >=(other : SpValue::Raw) : Bool\n"
  "    sp_scalar_cmp(@v, other) >= 0\n"
  "  end\n"
  "\n"
  "  # Dispatch: an object kind forwards to its class's sp_send; a scalar answers\n"
  "  # the handful of methods the boxed paths reach. A name the runtime does not\n"
  "  # know raises, matching Ruby's NoMethodError rather than silently answering.\n"
  "  def sp_send(name : String, args : Array(SpValue)) : SpValue\n"
  "    case v = @v\n"
  "    when SpObject then v.sp_send(name, args)\n"
  "    else               sp_scalar_send(@v, name, args)\n"
  "    end\n"
  "  end\n"
  "\n"
  "  def call(args : Array(SpValue)) : SpValue\n"
  "    sp_send(\"call\", args)\n"
  "  end\n"
  "\n"
  "  def call : SpValue\n"
  "    sp_send(\"call\", [] of SpValue)\n"
  "  end\n"
  "end\n"
  "\n"
  "def sp_box(v : SpValue) : SpValue\n"
  "  v\n"
  "end\n"
  "\n"
  "def sp_box(v : SpValue::Raw) : SpValue\n"
  "  SpValue.new(v)\n"
  "end\n"
  "\n"
  "# A class value (a metaclass) is not a Raw member and matches no per-class\n"
  "# overload, so it boxes through the wrapper too; a poly slot can hold one\n"
  "# (`k = cond ? A : B`).\n"
  "def sp_box(v : T.class) : SpValue forall T\n"
  "  SpValue.new(SpBox.new(v))\n"
  "end\n"
  "\n"
  "# A stdlib container is likewise not a Raw member. The wrapper carries it and\n"
  "# forwards inspect/to_s; container-specific dispatch is a later step.\n"
  "def sp_box(v : Array(T)) : SpValue forall T\n"
  "  SpValue.new(SpBox.new(v))\n"
  "end\n"
  "\n"
  "def sp_box(v : Hash(K, V)) : SpValue forall K, V\n"
  "  SpValue.new(SpBox.new(v))\n"
  "end\n"
  "\n"
  "def sp_box(v : Range(B, E)) : SpValue forall B, E\n"
  "  SpValue.new(SpBox.new(v))\n"
  "end\n"
  "\n"
  "# P21 boxes only scalars into a widened container: they are members of Raw, so\n"
  "# the overload above is all a push needs. A user object or a stdlib container\n"
  "# (Array/Hash/Range) cannot ride the union without a wrapper that inherits\n"
  "# SpObject -- that is P22's SpBox work, and the emitter refuses such an element\n"
  "# rather than emit a push with no overload to answer it.\n"
  "def sp_scalar_add(a : SpValue::Raw, b : SpValue::Raw) : SpValue::Raw\n"
  "  if a.is_a?(Int64) && b.is_a?(Int64)\n"
  "    a + b\n"
  "  elsif a.is_a?(String) && b.is_a?(String)\n"
  "    a + b\n"
  "  elsif (a.is_a?(Int64) || a.is_a?(Float64)) && (b.is_a?(Int64) || b.is_a?(Float64))\n"
  "    a.to_f + b.to_f\n"
  "  else\n"
  "    raise ArgumentError.new(\"unsupported operand\")\n"
  "  end\n"
  "end\n"
  "\n"
  "def sp_scalar_sub(a : SpValue::Raw, b : SpValue::Raw) : SpValue::Raw\n"
  "  if a.is_a?(Int64) && b.is_a?(Int64)\n"
  "    a - b\n"
  "  elsif (a.is_a?(Int64) || a.is_a?(Float64)) && (b.is_a?(Int64) || b.is_a?(Float64))\n"
  "    a.to_f - b.to_f\n"
  "  else\n"
  "    raise ArgumentError.new(\"unsupported operand\")\n"
  "  end\n"
  "end\n"
  "\n"
  "def sp_scalar_mul(a : SpValue::Raw, b : SpValue::Raw) : SpValue::Raw\n"
  "  if a.is_a?(Int64) && b.is_a?(Int64)\n"
  "    a * b\n"
  "  elsif a.is_a?(String) && b.is_a?(Int64)\n"
  "    a * b\n"
  "  elsif (a.is_a?(Int64) || a.is_a?(Float64)) && (b.is_a?(Int64) || b.is_a?(Float64))\n"
  "    a.to_f * b.to_f\n"
  "  else\n"
  "    raise ArgumentError.new(\"unsupported operand\")\n"
  "  end\n"
  "end\n"
  "\n"
  "def sp_scalar_div(a : SpValue::Raw, b : SpValue::Raw) : SpValue::Raw\n"
  "  if a.is_a?(Int64) && b.is_a?(Int64)\n"
  "    a // b\n"
  "  elsif (a.is_a?(Int64) || a.is_a?(Float64)) && (b.is_a?(Int64) || b.is_a?(Float64))\n"
  "    a.to_f / b.to_f\n"
  "  else\n"
  "    raise ArgumentError.new(\"unsupported operand\")\n"
  "  end\n"
  "end\n"
  "\n"
  "def sp_scalar_cmp(a : SpValue::Raw, b : SpValue::Raw) : Int32\n"
  "  if a.is_a?(Int64) && b.is_a?(Int64)\n"
  "    (a <=> b).not_nil!\n"
  "  elsif a.is_a?(String) && b.is_a?(String)\n"
  "    (a <=> b).not_nil!\n"
  "  elsif (a.is_a?(Int64) || a.is_a?(Float64)) && (b.is_a?(Int64) || b.is_a?(Float64))\n"
  "    (a.to_f <=> b.to_f).not_nil!\n"
  "  else\n"
  "    raise ArgumentError.new(\"unsupported comparison\")\n"
  "  end\n"
  "end\n"
  "\n"
  "def sp_scalar_send(v : SpValue::Raw, name : String, args : Array(SpValue)) : SpValue\n"
  "  case name\n"
  "  when \"to_i\"    then sp_box(sp_to_i(v))\n"
  "  when \"to_f\"    then sp_box(sp_to_f(v))\n"
  "  when \"to_s\"    then sp_box(v.to_s)\n"
  "  when \"nil?\"    then sp_box(v.nil?)\n"
  "  when \"inspect\" then sp_box(v.inspect)\n"
  "  when \"+\"       then sp_box(sp_scalar_add(v, args[0].raw))\n"
  "  when \"-\"       then sp_box(sp_scalar_sub(v, args[0].raw))\n"
  "  when \"*\"       then sp_box(sp_scalar_mul(v, args[0].raw))\n"
  "  when \"/\"       then sp_box(sp_scalar_div(v, args[0].raw))\n"
  "  when \"<\"       then sp_box(sp_scalar_cmp(v, args[0].raw) < 0)\n"
  "  when \"<=\"      then sp_box(sp_scalar_cmp(v, args[0].raw) <= 0)\n"
  "  when \">\"       then sp_box(sp_scalar_cmp(v, args[0].raw) > 0)\n"
  "  when \">=\"      then sp_box(sp_scalar_cmp(v, args[0].raw) >= 0)\n"
  "  when \"==\"      then sp_box(v == args[0].raw)\n"
  "  else                raise ArgumentError.new(\"undefined method '#{name}'\")\n"
  "  end\n"
  "end\n"
  "\n"
  "def sp_to_i(v : SpValue::Raw) : Int64\n"
  "  case v\n"
  "  when Int64   then v\n"
  "  when Float64 then v.to_i64\n"
  "  when String  then v.to_i64(strict: false) { 0_i64 }\n"
  "  when Bool    then v ? 1_i64 : 0_i64\n"
  "  else              0_i64\n"
  "  end\n"
  "end\n"
  "\n"
  "def sp_to_f(v : SpValue::Raw) : Float64\n"
  "  case v\n"
  "  when Int64   then v.to_f\n"
  "  when Float64 then v\n"
  "  when String  then v.to_f\n"
  "  when Bool    then v ? 1.0 : 0.0\n"
  "  else              0.0\n"
  "  end\n"
  "end\n"
  "\n"
  "def sp_unbox_i(v : SpValue) : Int64\n"
  "  v.to_i\n"
  "end\n"
  "\n"
  "def sp_unbox_f(v : SpValue) : Float64\n"
  "  v.to_f\n"
  "end\n"
  "\n"
  "def sp_unbox_s(v : SpValue) : String\n"
  "  v.raw.to_s\n"
  "end\n"
  "\n"
  "def sp_unbox_b(v : SpValue) : Bool\n"
  "  v.truthy?\n"
  "end\n"
  "\n"
  "def sp_unbox_sym(v : SpValue) : Symbol\n"
  "  raw = v.raw\n"
  "  raw.is_a?(Symbol) ? raw : raw.to_s.to_sym\n"
  "end\n"
  "\n"
  "def sp_unbox_call(v : SpValue) : SpValue\n"
  "  v\n"
  "end\n"
  "\n"
  ;

#endif /* SPINEL_CRYSTAL_RUNTIME_H */
